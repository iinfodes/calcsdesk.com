// Focused keyboard/ARIA regression review in an isolated headless browser.
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const req = createRequire('C:/Program Files/WindowsApps/OpenAI.CodexPrimaryRuntime.v26-1026-487-0_26.1026.487.0_x64__3k8sg7r9htsxt/dependencies/node/node_modules/playwright/package.json');
const { chromium } = req('playwright');
const checks = [];
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); };
(async () => {
  const root = path.resolve('dist');
  const server = http.createServer((request, response) => {
    const pathname = new URL(request.url, 'http://localhost').pathname;
    const file = path.resolve(root, '.' + (pathname.endsWith('/') ? pathname + 'index.html' : pathname));
    if (!file.startsWith(root + path.sep) || !fs.existsSync(file)) { response.writeHead(404); response.end(); return; }
    response.setHeader('Content-Type', ({ '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css' })[path.extname(file)] || 'application/octet-stream');
    response.end(fs.readFileSync(file));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  try {
    const page = await browser.newPage({ reducedMotion: 'reduce' });
    const base = `http://127.0.0.1:${server.address().port}`;
    await page.goto(base);
    await page.locator('astro-island:not([ssr])').waitFor();
    await page.locator('#calculator-search').fill('federal');
    await page.locator('#calculator-search').press('Enter');
    check('Search submit moves keyboard focus to results heading', await page.locator('#directory-title').evaluate(el => document.activeElement === el));
    await page.keyboard.press('Tab');
    check('Tab from results reaches preparation filter', await page.locator('.planned-toggle input').evaluate(el => document.activeElement === el));
    check('Reduced motion disables smooth scrolling', await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior === 'auto'));
    await page.goto(base + '/us/');
    await page.locator('astro-island:not([ssr])').waitFor();
    check('Fixed country group has an accessible name', await page.getByRole('group', { name: 'Your country' }).count() === 1);
    check('Change-country link identifies its purpose', await page.getByRole('link', { name: 'Change country from United States' }).count() === 1);
    await page.goto(base + '/us/tax/income-tax-calculator/');
    await page.locator('astro-island:not([ssr])').waitFor();
    await page.locator('#filing-status').selectOption('married_joint');
    await page.locator('#annual-wages').fill('9000000');
    await page.locator('#spouse-wages').fill('2000000');
    check('Combined-limit error marks both wage fields invalid', await page.locator('#annual-wages').getAttribute('aria-invalid') === 'true' && await page.locator('#spouse-wages').getAttribute('aria-invalid') === 'true');
    check('Combined-limit error has explanatory alert', (await page.getByRole('alert').textContent()).includes('Combined wages'));
    const status = page.locator('.calculator-results > .sr-only[role="status"]');
    await status.evaluate(el => { window.reviewResultStatus = el; });
    check('Invalid estimate has persistent status message', (await status.textContent()).includes('unavailable'));
    await page.locator('#annual-wages').fill('75000');
    await page.locator('#spouse-wages').fill('0');
    check('Validation recovery retains the same live-region element', await status.evaluate(el => window.reviewResultStatus === el));
    check('Valid estimate status includes amount and annual period', /Annual regular federal income tax before credits: \$/.test(await status.textContent()));
    await page.getByRole('button', { name: 'Monthly average', exact: true }).click();
    check('Period switch updates accessible announcement', (await status.textContent()).startsWith('Monthly average'));
    const tableRegion = page.getByRole('region', { name: 'Annual regular income tax calculation', exact: true });
    await tableRegion.focus();
    check('Scrollable working table is keyboard focusable and named', await tableRegion.evaluate(el => document.activeElement === el));
    check('Recovered inputs no longer marked invalid', await page.locator('#annual-wages').getAttribute('aria-invalid') === 'false' && await page.locator('#spouse-wages').getAttribute('aria-invalid') === 'false');
    await page.goto(base + '/us/tax/income-tax-calculator/');
    await page.locator('astro-island:not([ssr])').waitFor();
    const compareToggle = page.getByRole('checkbox', { name: 'Compare with a second scenario' });
    check('Comparison is optional and hidden by default', !await compareToggle.isChecked() && !await page.locator('#comparison-details').isVisible());
    const requests = [];
    page.on('request', request => requests.push(request.url()));
    const storageBefore = await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }));
    await compareToggle.focus();
    await page.keyboard.press('Space');
    check('Keyboard Space opens comparison', await page.locator('#comparison-details').isVisible());
    await page.keyboard.press('Tab');
    check('Keyboard reaches named scenario B control', await page.locator('#comparison-status').evaluate(el => document.activeElement === el));
    await page.locator('#comparison-status').selectOption('married_joint');
    await page.locator('#comparison-wages').fill('90000');
    await page.locator('#comparison-spouse').fill('60000');
    const comparisonRow = label => page.locator('.comparison-table tbody tr').filter({ has: page.getByRole('rowheader', { name: label, exact: true }) });
    const bTax = await comparisonRow('Regular federal income tax before credits').locator('td').nth(1).textContent();
    const bPayroll = await comparisonRow('Employee payroll taxes').locator('td').nth(1).textContent();
    const bTotal = await comparisonRow('Modeled federal taxes').locator('td').nth(1).textContent();
    const comparisonCells = await page.locator('.comparison-table tbody tr').evaluateAll(rows => rows.map(row => [...row.querySelectorAll('td')].map(cell => cell.textContent)));
    const numeric = value => Number(value.replaceAll('−', '-').replace(/[^\d.\-]/g, ''));
    check('Unequal-scenario differences equal B minus A for every metric', comparisonCells.every(([a, b, change]) => Math.abs(numeric(b) - numeric(a) - numeric(change)) < 0.001));
    await page.locator('#filing-status').selectOption('married_joint');
    await page.locator('#annual-wages').fill('90000');
    await page.locator('#spouse-wages').fill('60000');
    check('Scenario B tax equals standalone engine output for identical inputs', bTax === await page.locator('[data-testid="income-tax"]').textContent());
    check('Scenario B total equals standalone engine output for identical inputs', bTotal === await page.locator('[data-testid="total-federal"]').textContent());
    check('Equal scenarios have zero differences for every metric', (await page.locator('.comparison-table tbody tr td:last-child').allTextContents()).every(value => value === '$0.00'));
    check('Comparison payroll matches sourced joint illustration', bPayroll === '$11,475.00');
    await page.getByRole('button', { name: 'Monthly average', exact: true }).click();
    check('Comparison remains annual when main result switches period', bTotal === await comparisonRow('Modeled federal taxes').locator('td').nth(1).textContent() && (await page.locator('#comparison-caption').textContent()).startsWith('Annual'));
    await page.locator('#comparison-wages').fill('10000000');
    check('Invalid comparison hides stale results', !await page.locator('.comparison-table').count() && (await page.locator('#comparison-error').textContent()).includes('Combined'));
    check('Invalid comparison marks both B inputs', await page.locator('#comparison-wages').getAttribute('aria-invalid') === 'true' && await page.locator('#comparison-spouse').getAttribute('aria-invalid') === 'true');
    await page.locator('#comparison-wages').fill('95000');
    await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.reviewSharedUrl = text; } } }));
    await page.getByRole('button', { name: 'Copy estimate link' }).click();
    const shared = await page.evaluate(() => window.reviewSharedUrl);
    check('Estimate share includes only scenario A in canonical v1 format', new URL(shared).hash === '#v=1&status=married_joint&wages=90000&spouse=60000');
    check('Comparison does not persist financial inputs', storageBefore === await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } })));
    check('Comparison edits make no network requests', requests.length === 0);
    await page.setViewportSize({ width: 375, height: 812 });
    check('Mobile page does not overflow horizontally', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    check('Mobile comparison scrolls inside its named region', await page.locator('.comparison-table').evaluate(el => el.scrollWidth > el.clientWidth));
    const screenshotDir = path.resolve(process.env.CALCSDESK_REVIEW_OUT || 'design/selected');
    fs.mkdirSync(screenshotDir, { recursive: true });
    await page.locator('.scenario-comparison').screenshot({ path: path.join(screenshotDir, 'comparison-mobile.png') });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('.scenario-comparison').screenshot({ path: path.join(screenshotDir, 'comparison-desktop.png') });
    await page.emulateMedia({ media: 'print' });
    check('Visible comparison remains present in print', await page.locator('.comparison-table').isVisible());
    await page.emulateMedia({ media: 'screen' });
    await compareToggle.uncheck();
    await page.emulateMedia({ media: 'print' });
    check('Closed comparison is excluded from print', !await page.locator('.comparison-table').isVisible());
    await page.emulateMedia({ media: 'screen' });
    await page.evaluate(() => { location.hash = 'status=single&wages=12345'; });
    await page.waitForFunction(() => document.querySelector('#filing-status').value === 'single' && document.querySelector('#annual-wages').value === '12345');
    check('Legacy shared estimate restores atomically', !await page.locator('#spouse-wages').count());
    await page.evaluate(() => { location.hash = 'status=married_joint&wages=80000'; });
    await page.waitForTimeout(50);
    check('Partial joint fragment leaves the whole current scenario unchanged', await page.locator('#filing-status').inputValue() === 'single' && await page.locator('#annual-wages').inputValue() === '12345');
    await page.evaluate(() => { location.hash = 'v=1&status=married_joint&wages=80000&spouse=20000'; });
    await page.waitForFunction(() => document.querySelector('#spouse-wages')?.value === '20000');
    check('Versioned shared estimate restores all fields', await page.locator('#filing-status').inputValue() === 'married_joint' && await page.locator('#annual-wages').inputValue() === '80000');
    await page.evaluate(() => { location.hash = 'status=single&wages=1&wages=2'; });
    await page.waitForTimeout(50);
    check('Duplicate shared amount leaves all restored fields unchanged', await page.locator('#filing-status').inputValue() === 'married_joint' && await page.locator('#annual-wages').inputValue() === '80000' && await page.locator('#spouse-wages').inputValue() === '20000');
    console.log(JSON.stringify({ checks: checks.length, passed: checks }, null, 2));
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
